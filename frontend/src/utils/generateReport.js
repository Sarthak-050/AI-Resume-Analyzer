import jsPDF from "jspdf";

/**
 * Generates and downloads a PDF report summarizing the AI resume analysis.
 */
export function generateAIReport(resume) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });

  const pageWidth = doc.internal.pageSize.getWidth();
  const marginX = 48;
  let y = 60;

  const brandColor = [67, 56, 202]; // indigo
  const inkColor = [23, 28, 44];
  const grayColor = [110, 118, 140];
  const scanColor = [13, 148, 136];
  const roseColor = [225, 29, 72];

  // Header
  doc.setFillColor(...brandColor);
  doc.rect(0, 0, pageWidth, 90, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.text("AI Resume Analysis Report", marginX, 45);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.text(resume.resumeName || "Resume", marginX, 68);

  y = 130;

  // Score
  const score = resume.analysis?.atsScore ?? 0;
  doc.setTextColor(...inkColor);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text("ATS Score", marginX, y);

  doc.setFontSize(36);
  doc.setTextColor(...brandColor);
  doc.text(`${score} / 100`, marginX, y + 40);

  doc.setFontSize(9);
  doc.setTextColor(...grayColor);
  doc.setFont("helvetica", "normal");
  doc.text(
    `Generated on ${new Date().toLocaleDateString("en-US", {
      month: "long",
      day: "numeric",
      year: "numeric",
    })}`,
    marginX,
    y + 58
  );

  y += 90;

  // Section helper
  const drawSection = (title, items, color, emptyText) => {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(13);
    doc.setTextColor(...inkColor);
    doc.text(title, marginX, y);
    y += 20;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(10.5);

    if (!items || items.length === 0) {
      doc.setTextColor(...grayColor);
      doc.text(emptyText, marginX, y);
      y += 24;
      return;
    }

    items.forEach((item) => {
      const text = typeof item === "string" ? item : JSON.stringify(item);

      if (y > 760) {
        doc.addPage();
        y = 60;
      }

      doc.setTextColor(...color);
      doc.text("•", marginX, y);

      doc.setTextColor(...inkColor);
      const wrapped = doc.splitTextToSize(text, pageWidth - marginX * 2 - 15);
      doc.text(wrapped, marginX + 14, y);
      y += wrapped.length * 14 + 6;
    });

    y += 14;
  };

  drawSection(
    "AI Improvement Suggestions",
    resume.analysis?.resumeImprovements,
    brandColor,
    "No suggestions available."
  );

  drawSection(
    "Strong Skills",
    resume.analysis?.strongSkills,
    scanColor,
    "No strong skills detected."
  );

  drawSection(
    "Missing Skills",
    resume.analysis?.missingSkills,
    roseColor,
    "No missing skills detected."
  );

  // Footer
  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8.5);
    doc.setTextColor(...grayColor);
    doc.text(
      "Generated by AI Resume Analyzer",
      marginX,
      doc.internal.pageSize.getHeight() - 30
    );
  }

  const fileName = `${(resume.resumeName || "resume").replace(
    /\.pdf$/i,
    ""
  )}-AI-Report.pdf`;

  doc.save(fileName);
}